"""Write the built-in definitions (data/glossary/glossary.md) as a C++ table.

Usage: python3 -I make_glossary_table.py glossary.md > src/core/glossary/glossary_table.hpp
       python3 -I make_glossary_table.py --check glossary.md src/core/glossary/glossary_table.hpp
  The first form writes the table; the second exits with status 1 when
  the table is not the one glossary.md gives (a test runs it).
  Each "## TITLE" heading of glossary.md starts an entry, whose text runs
  to the next heading (Markdown, kept as is). KEYS below gives each title
  its key (the name `primerpicker explain` takes) and aliases; a title
  missing from KEYS is an error.
"""
import sys

# title: (key, aliases), in the order of glossary.md
KEYS = {
    'Primer': ('primer', ()),
    'Template': ('template', ()),
    'Amplicon (PCR product)': ('amplicon', ('product', 'pcr-product')),
    "5' extension": ('extension', ("5'-extension", '5-extension')),
    '%GC (GC content)': ('gc', ('%gc', 'gc-content')),
    'Melting temperature (Tm) of a primer': ('tm', ('melting-temperature',)),
    'Product Tm': ('product-tm', ()),
    'Annealing temperature (Ta)': ('annealing-temperature', ('ta',)),
    'Hairpin': ('hairpin', ('hairpins',)),
    'Primer-dimer': ('dimer', ('dimers', 'primer-dimer', "3'-dimers")),
    'Runs': ('runs', ('run',)),
    "3' G/C run (GC clamp)": ('gc-clamp', ("3'-gc-run", 'gc-run')),
    'Criteria and "Meets criteria"': ('criteria', ('meets-criteria',)),
    'Primer balance (pair)': ('balance', ('primer-balance', 'pair')),
    'Uniqueness': ('uniqueness', ('homology',)),
    'False priming': ('false-priming', ()),
    'Match Active Primer': ('match', ('match-active-primer',)),
    'Find Pair and its score': ('find-pair', ('score',)),
    'Restriction sites (true and almost sites)': ('restriction-sites', ('enzymes', 'restriction-enzymes')),
    'True site and almost site': ('almost-site', ('true-site', 'almost-sites', 'true-sites')),
    'Circular molecule': ('circular', ('circular-molecule', 'plasmid')),
    'Multi Primer Analysis': ('multi-primer', ('multi',)),
    'Nested primers': ('nested-primers', ('nested',)),
    'Sequencing primer': ('sequencing-primer', ('sequencing',)),
    'Mutagenize': ('mutagenize', ('mutagenesis',)),
}

HEADER = '''#pragma once

// Generated by data/glossary/make_glossary_table.py from
// data/glossary/glossary.md: do not edit.

#include "core/glossary/glossary_entry.hpp"

#include <array>

namespace primerpicker::glossary {{

// The {count} built-in definitions, in the order of glossary.md
inline constexpr auto glossary_table = std::array<Entry, {count}>{{{{
'''

FOOTER = '''}};

}  // namespace primerpicker::glossary
'''

DELIMITER = 'glossary'


def entries(text):
    """(title, body) pairs of the '## ' sections"""
    sections = []
    for line in text.splitlines():
        if line.startswith('## '):
            sections.append([line[3:].strip(), []])
        elif sections:
            sections[-1][1].append(line)
    return [(title, '\n'.join(lines).strip() + '\n') for title, lines in sections]


def cpp_string(text):
    if ')' + DELIMITER + '"' in text:
        sys.exit('an entry contains the raw string delimiter')
    return 'R"' + DELIMITER + '(' + text + ')' + DELIMITER + '"'


def table(markdown):
    sections = entries(markdown)
    unknown = [title for title, _ in sections if title not in KEYS]
    if unknown:
        sys.exit('no key for: ' + ', '.join(unknown))
    rows = []
    for title, body in sections:
        key, aliases = KEYS[title]
        rows.append('    Entry{{.key = "{}",\n          .aliases = "{}",\n          .title = {},\n'
                    '          .text = {}}},\n'.format(key, ' '.join(aliases), cpp_string(title), cpp_string(body)))
    return HEADER.format(count=len(rows)) + ''.join(rows) + FOOTER


def main(arguments):
    if arguments[:1] == ['--check'] and len(arguments) == 3:
        markdown = open(arguments[1], encoding='utf-8').read()
        current = open(arguments[2], encoding='utf-8').read()
        if table(markdown) != current:
            sys.exit(arguments[2] + ' is not up to date with ' + arguments[1])
        return
    if len(arguments) != 1:
        sys.exit(__doc__)
    sys.stdout.write(table(open(arguments[0], encoding='utf-8').read()))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main(sys.argv[1:])
