"""Write REBASE enzymes as C++ tables.

Usage: python3 -I make_enzyme_table.py REBASE_DIR VERSION > src/core/enzymes/rebase_table.hpp
       python3 -I make_enzyme_table.py REBASE_DIR VERSION others > src/core/enzymes/rebase_other_table.hpp
  The first form writes the commercially available enzymes, from
  REBASE_DIR/emboss_e.VERSION (patterns and cuts) and
  REBASE_DIR/emboss_r.VERSION (suppliers); an enzyme is commercially
  available when it has at least one supplier.
  The second form writes the other REBASE enzymes whose recognition
  sequence is known (one site, IUPAC letters), from
  REBASE_DIR/withrefm.VERSION; their cuts are converted to the EMBOSS
  numbering (G^AATTC: 1 5; GAAGAC(2/6): 8 12; ^GATC: -1 4), and are
  unknown (0) when withrefm does not give both strands (CASTGNN^,
  GGCGCA(?/2)).
"""
import re
import sys
from pathlib import Path

IUPAC = re.compile(r'[ACGTRYSWKMBDHVN]+')
NAME = re.compile(r'[A-Za-z0-9-]+')
SUPPLIERS = re.compile(r'[A-Z]+')

HEADER = '''#pragma once

// Generated by data/rebase/make_enzyme_table.py from REBASE version
// {version} (data/rebase/README.md): do not edit.
//
// Roberts RJ, Vincze T, Posfai J, Macelis D (2010) REBASE--a database
// for DNA restriction and modification: enzymes, genes and genomes.
// Nucl. Acids Res. 38:D234-D236. http://rebase.neb.com

#include "core/enzymes/enzyme.hpp"

#include <array>

namespace primerpicker::enzymes {{

// The {count} commercially available enzymes of REBASE {version}, by
// name (byte order)
inline constexpr auto rebase_table = std::array<Enzyme, {count}>{{{{
'''

OTHERS_HEADER = '''#pragma once

// Generated by data/rebase/make_enzyme_table.py from REBASE version
// {version} (data/rebase/README.md): do not edit.
//
// Roberts RJ, Vincze T, Posfai J, Macelis D (2010) REBASE--a database
// for DNA restriction and modification: enzymes, genes and genomes.
// Nucl. Acids Res. 38:D234-D236. http://rebase.neb.com

#include "core/enzymes/enzyme.hpp"

#include <array>

namespace primerpicker::enzymes {{

// The {count} REBASE {version} enzymes that are not commercially
// available and have a known recognition sequence, by name (byte order)
inline constexpr auto rebase_other_table = std::array<Enzyme, {count}>{{{{
'''

FOOTER = '''}};

}  // namespace primerpicker::enzymes
'''


def data_lines(path):
    for line in path.read_text(encoding='ascii').splitlines():
        if line and not line.startswith('#'):
            yield line


def patterns(path):
    """name -> (pattern, length, ncuts, c1, c2, c3, c4), from emboss_e"""
    table = {}
    for line in data_lines(path):
        name, pattern, *numbers = line.split()
        if len(numbers) != 7:
            raise SystemExit(f'unexpected emboss_e line: {line}')
        length, ncuts, _blunt, *cuts = (int(number) for number in numbers)
        table[name] = (pattern, length, ncuts, *cuts)
    return table


def suppliers(path):
    """name -> supplier codes, from emboss_r (entries end with //)"""
    table, entry = {}, []
    for line in path.read_text(encoding='ascii').splitlines():
        if line.startswith('#'):
            continue
        if line == '//':
            name, codes = entry[0], entry[5].strip() if len(entry) > 5 else ''
            if codes and SUPPLIERS.fullmatch(codes) is None:
                raise SystemExit(f'unexpected suppliers for {name}: {codes}')
            table[name] = codes
            entry = []
        else:
            entry.append(line)
    return table


def emboss_residue(bases_before_cut):
    """A cut between bases, as EMBOSS numbers it (no 0: -1 is before
    the first base)"""
    return bases_before_cut if bases_before_cut >= 1 else bases_before_cut - 1


def withrefm_entries(path):
    """name -> (recognition sequence as written, suppliers)"""
    entries, fields = {}, {}
    for line in path.read_text(encoding='latin-1').splitlines() + ['<1>']:
        match = re.match(r'<(\d)>(.*)', line)
        if match is None:
            continue
        if match.group(1) == '1' and fields:
            entries[fields['1']] = (fields.get('3', ''), fields.get('7', ''))
            fields = {}
        fields[match.group(1)] = match.group(2)
    return entries


def withrefm_site(written):
    """(pattern, ncuts, c1, c2, c3, c4) of a withrefm recognition
    sequence, or None when it is unknown or not a single site"""
    if (match := re.fullmatch(r'([A-Z]*)\^([A-Z]+)', written)) is not None:
        pattern, before = match.group(1) + match.group(2), len(match.group(1))
        return pattern, 2, emboss_residue(before), emboss_residue(len(pattern) - before), 0, 0
    if (match := re.fullmatch(r'([A-Z]+)\((-?\d+)/(-?\d+)\)', written)) is not None:
        pattern, top, bottom = match.group(1), int(match.group(2)), int(match.group(3))
        return pattern, 2, emboss_residue(len(pattern) + top), emboss_residue(len(pattern) + bottom), 0, 0
    if (match := re.fullmatch(r'\((-?\d+)/(-?\d+)\)([A-Z]+)\((-?\d+)/(-?\d+)\)', written)) is not None:
        first_top, first_bottom, pattern, second_top, second_bottom = match.groups()
        return (pattern, 4, emboss_residue(-int(first_top)), emboss_residue(-int(first_bottom)),
                emboss_residue(len(pattern) + int(second_top)), emboss_residue(len(pattern) + int(second_bottom)))
    pattern = re.sub(r'\^|\(.*?\)', '', written)  # cuts not known on both strands
    if IUPAC.fullmatch(pattern) is not None:
        return pattern, 0, 0, 0, 0, 0
    return None


def write_enzyme(out, name, pattern, ncuts, cuts, suppliers):
    first, second = cuts[:2], cuts[2:]
    out.write(f'    Enzyme{{.name = "{name}",\n'
              f'           .site = "{pattern}",\n'
              f'           .cut_count = {ncuts},\n'
              f'           .cuts = {{{{{{{first[0]}, {first[1]}}}, {{{second[0]}, {second[1]}}}}}}},\n'
              f'           .suppliers = "{suppliers}"}},\n')


def main(directory, version, which='commercial'):
    directory = Path(directory)
    sources = suppliers(directory / f'emboss_r.{version}')
    commercial = sorted(name for name, codes in sources.items() if codes)  # byte order, as std::less
    out = sys.stdout
    if which == 'others':
        entries = withrefm_entries(directory / f'withrefm.{version}')
        others = []
        for name in sorted(entries):
            if name in sources and sources[name] or NAME.fullmatch(name) is None:
                continue
            site = withrefm_site(entries[name][0])
            if site is not None:
                others.append((name, site))
        out.write(OTHERS_HEADER.format(version=version, count=len(others)))
        for name, (pattern, ncuts, *cuts) in others:
            write_enzyme(out, name, pattern, ncuts, cuts, '')
        out.write(FOOTER)
        return
    sites = patterns(directory / f'emboss_e.{version}')
    for name in commercial:
        if name not in sites or NAME.fullmatch(name) is None:
            raise SystemExit(f'no usable pattern for {name}')
        pattern, length = sites[name][:2]
        if IUPAC.fullmatch(pattern) is None or length != len(pattern):
            raise SystemExit(f'unexpected pattern for {name}: {pattern}')
    out.write(HEADER.format(version=version, count=len(commercial)))
    for name in commercial:
        pattern, _length, ncuts, *cuts = sites[name]
        write_enzyme(out, name, pattern, ncuts, cuts, sources[name])
    out.write(FOOTER)


if __name__ == '__main__':
    main(*sys.argv[1:])
